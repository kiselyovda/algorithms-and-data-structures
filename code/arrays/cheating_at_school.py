# В школе прошёл экзамен по математике.
# Некоторые ученики списали решения, были замечены и получили 0 баллов.
# Помогите учителю пересортировать оценки учеников.
# Все оценки, равные 0, должны быть перемещены в конец списка,
# при этом порядок остальных оценок должен остаться неизменным.

# Формат входных данных
# В первой строке задаётся число N — размер массива (количество оценок).
# Во второй строке вводится массив из N целых чисел, разделённых пробелами.

# Формат выходных данных
# На выходе программа должна вывести строку из N элементов массива,
# где все нули перемещены в конец, а порядок остальных чисел сохранён.
# Значения разделяются пробелами.

# Пример
# Входные данные
# 6
# 0 0 6 0 9 8
# Выходные данные
# 6 9 8 0 0 0

def solution(length: int, marks: list[int]) -> str:
    left = 0
    tmp = [0] * length
    pos = 0
    while left < length:
        if marks[left] != 0:
            tmp[pos] = marks[left]
            pos += 1
        left += 1
    return " ".join(map(str, tmp))


def main() -> None:
    length = int(input())
    marks = list(map(int, input().split(" ")))
    result = solution(length, marks)
    print(result)


if __name__ == '__main__':
    main()
